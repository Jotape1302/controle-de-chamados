-- Schema inicial. SQL compatível com PostgreSQL e com H2 (modo PostgreSQL).

CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    VARCHAR(50)  NOT NULL,
    password    VARCHAR(255) NOT NULL,
    full_name   VARCHAR(100) NOT NULL,
    email       VARCHAR(100) NOT NULL,
    admin       BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_users_username UNIQUE (username)
);

CREATE TABLE tickets (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         VARCHAR(150)  NOT NULL,
    description   VARCHAR(2000) NOT NULL,
    status        VARCHAR(20)   NOT NULL,
    priority      VARCHAR(20)   NOT NULL,
    requester     VARCHAR(50)   NOT NULL,
    category      VARCHAR(50)   NOT NULL,
    assigned_to   VARCHAR(50),
    created_at    TIMESTAMP(6)  NOT NULL,
    updated_at    TIMESTAMP(6)  NOT NULL,
    resolved_at   TIMESTAMP(6),
    sla_deadline  TIMESTAMP(6),
    CONSTRAINT ck_tickets_status   CHECK (status   IN ('OPEN', 'IN_PROGRESS', 'RESOLVED', 'CLOSED')),
    CONSTRAINT ck_tickets_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL'))
);

CREATE INDEX idx_tickets_status     ON tickets (status);
CREATE INDEX idx_tickets_priority   ON tickets (priority);
CREATE INDEX idx_tickets_requester  ON tickets (requester);
CREATE INDEX idx_tickets_created_at ON tickets (created_at);
